import { describe, expect, it } from 'vitest';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createDemoState, createEmptyState } from '../src/domain/seed';
import {
  DEFAULT_MADRASAH_IDENTITY,
  OFFICIAL_KOP_ASSET_PATH,
  formatKopAddressLine,
  formatKopRegistryLine,
  resolveEffectiveKopData,
  splitSchoolTitleForKop,
} from '../src/domain/kopIdentity';
import { OfficialKopSuratPreview } from '../src/components/OfficialKopSuratPreview';
import { SettingsScreen } from '../src/components/SettingsScreen';
import { SchedulePdfExportModal } from '../src/components/SchedulePdfExportModal';
import { AttendancePdfExportModal } from '../src/components/AttendancePdfExportModal';
import { DocumentIntakeForm } from '../src/components/persuratan/DocumentIntakeForm';
import { DocumentStudio } from '../src/components/persuratan/DocumentStudio';
import { DocumentPreviewFinalize } from '../src/components/persuratan/DocumentPreviewFinalize';
import { DocumentArchiveDetail } from '../src/components/persuratan/DocumentArchiveDetail';
import { TemplateGallery } from '../src/components/persuratan/TemplateGallery';
import { TemplateManager } from '../src/components/persuratan/TemplateManager';
import { SYSTEM_DOCUMENT_TEMPLATES } from '../src/domain/persuratan/templates/registry';
import { saveIntakeDraftToState } from '../src/domain/persuratan/intake/draftEngine';
import {
  buildInitialStudioContentFromDraft,
  stripAutoGeneratedKopNodes,
} from '../src/domain/persuratan/studio/contentGenerator';
import { renderOfficialDocumentPdf } from '../src/domain/persuratan/finalization/pdfRenderer';
import { exportAgendaRegisterPdf } from '../src/domain/persuratan/archive/agendaExport';
import { createJsPDFDocument, renderOfficialKopSurat } from '../src/utils/pdfExport';

describe('Phase 14 — Official MTs Daruttafsir Al-Husaini Kop Surat & Cross-App Integration', () => {
  it('1. Seed & identity single source of truth match the uploaded letterhead verbatim', () => {
    const demo = createDemoState();
    const empty = createEmptyState();

    for (const s of [demo.settings, empty.settings]) {
      expect(s.schoolName).toBe('MADRASAH TSANAWIYAH (MTs) DARUTTAFSIR AL-HUSAINI');
      expect(s.ministry).toBe('Yayasan Pondok Pesantren Daruttafsir Al-husaini');
      expect(s.regionalOffice).toBe(
        'Akte No. 06 Tanggal 15 April Tahun 2021 Notaris : Dani Ardiati, S.H'
      );
      expect(s.legalDecree).toBe(
        'Keputusan Menkumham RI No. AHU-0013850.AH.01.12.Tahun 2021'
      );
      expect(s.nsm).toBe('121232760023');
      expect(s.npsn).toBe('20279680');
      expect(s.accreditation).toBe('TERAKREDITASI B');
      expect(s.address).toBe(
        'Parungkulon RT.04/06 Kel. Durenmekar , Kec. Bojongsari Kota Depok'
      );
      expect(s.city).toBe('Depok');
      expect(s.phone).toBe('(0251) 8612107');
      expect(s.kopMode).toBe('structured');
      expect(s.kopImageUrl).toBe(OFFICIAL_KOP_ASSET_PATH);
    }
  });

  it('2. Kop formatting helpers produce exact 2-line title, registry line, and address band', () => {
    expect(splitSchoolTitleForKop(DEFAULT_MADRASAH_IDENTITY.schoolName)).toEqual([
      'MADRASAH TSANAWIYAH (MTs)',
      'DARUTTAFSIR AL-HUSAINI',
    ]);
    expect(formatKopRegistryLine('121232760023', '20279680')).toBe(
      'NSM : 121232760023 NPSN 20279680'
    );
    expect(
      formatKopAddressLine({
        address: DEFAULT_MADRASAH_IDENTITY.address,
        city: DEFAULT_MADRASAH_IDENTITY.city,
        phone: DEFAULT_MADRASAH_IDENTITY.phone,
      })
    ).toBe(
      'Alamat : Parungkulon RT.04/06 Kel. Durenmekar , Kec. Bojongsari Kota Depok (0251) 8612107'
    );

    const resolved = resolveEffectiveKopData(createDemoState().settings, {
      kopMode: 'image',
    });
    expect(resolved.kopMode).toBe('image');
    expect(resolved.kopImageUrl).toBe(OFFICIAL_KOP_ASSET_PATH);
  });

  it('3. OfficialKopSuratPreview renders both structured letterhead and full-image banner modes', () => {
    const demo = createDemoState();

    const structuredHtml = renderToStaticMarkup(
      React.createElement(OfficialKopSuratPreview, {
        settings: demo.settings,
        variant: 'full',
      })
    );
    expect(structuredHtml).toContain('data-kop-mode="structured"');
    expect(structuredHtml).toContain('MADRASAH TSANAWIYAH (MTs)');
    expect(structuredHtml).toContain('DARUTTAFSIR AL-HUSAINI');
    expect(structuredHtml).toContain('Yayasan Pondok Pesantren Daruttafsir Al-husaini');
    expect(structuredHtml).toContain('Dani Ardiati, S.H');
    expect(structuredHtml).toContain('AHU-0013850.AH.01.12.Tahun 2021');
    expect(structuredHtml).toContain('NSM : 121232760023 NPSN 20279680');
    expect(structuredHtml).toContain('TERAKREDITASI B');
    expect(structuredHtml).toContain('Parungkulon RT.04/06');
    expect(structuredHtml).toContain('(0251) 8612107');

    const imageHtml = renderToStaticMarkup(
      React.createElement(OfficialKopSuratPreview, {
        settings: { ...demo.settings, kopMode: 'image' },
        variant: 'full',
      })
    );
    expect(imageHtml).toContain('data-kop-mode="image"');
    expect(imageHtml).toContain(OFFICIAL_KOP_ASSET_PATH);
  });

  it('4. jsPDF renderOfficialKopSurat and Buku Agenda PDF work cleanly across modes & compact layouts', () => {
    const demo = createDemoState();

    const docPortrait = createJsPDFDocument('portrait', 'a4');
    const yStructured = renderOfficialKopSurat(docPortrait, demo, 10, undefined, false);
    expect(yStructured).toBeGreaterThan(36);
    expect(yStructured).toBeLessThan(65);

    const docLandscape = createJsPDFDocument('landscape', 'a4');
    const yCompact = renderOfficialKopSurat(docLandscape, demo, 7, undefined, true);
    expect(yCompact).toBeGreaterThan(24);
    expect(yCompact).toBeLessThan(48);

    const docImageMode = createJsPDFDocument('portrait', 'a4');
    const yImage = renderOfficialKopSurat(
      docImageMode,
      { ...demo, settings: { ...demo.settings, kopMode: 'image' } },
      10,
      undefined,
      false
    );
    expect(yImage).toBeGreaterThan(30);

    const agendaPdf = exportAgendaRegisterPdf(demo.documents ?? [], demo, {
      periodLabel: 'Tahun Ajaran 2026/2027 · Semester Ganjil',
      saveFile: false,
    });
    expect(agendaPdf.bytes.byteLength).toBeGreaterThan(1000);
    expect(String.fromCharCode(...agendaPdf.bytes.slice(0, 5))).toBe('%PDF-');
  });

  it('5. Persuratan S03->S04->S05->PDF snapshots full Kop identity and prevents Kop duplication', async () => {
    const demo = createDemoState();
    const tpl01 = SYSTEM_DOCUMENT_TEMPLATES.find((t) => t.id === 'SYS-TPL-01')!;
    const activeTeacherId = demo.teachers.find((t) => t.isActive !== false)!.id;
    const saved = saveIntakeDraftToState(
      demo,
      tpl01,
      {
        peserta: [activeTeacherId],
        nama_kegiatan: 'Bimbingan Teknis Kurikulum Madrasah',
        penyelenggara: 'Kantor Kementerian Agama Kota Depok',
        tanggal_mulai: '2026-11-25',
        tanggal_selesai: '2026-11-26',
        lokasi: 'Aula MTs Daruttafsir Al-Husaini',
        dasar_surat: 'Surat Undangan No. B-412/Kk.10/XI/2026',
      },
      { timestamp: '2026-11-18T08:00:00Z' }
    );

    const kopSnap = saved.draft.sourceSnapshots.find(
      (s) => s.sourceKey === 'settings.madrasah_identity_signatory'
    );
    expect(kopSnap).toBeDefined();
    const captured = kopSnap!.capturedValue as Record<string, unknown>;
    expect(captured.schoolName).toBe(DEFAULT_MADRASAH_IDENTITY.schoolName);
    expect(captured.legalDecree).toBe(DEFAULT_MADRASAH_IDENTITY.legalDecree);
    expect(captured.accreditation).toBe(DEFAULT_MADRASAH_IDENTITY.accreditation);
    expect(captured.nsm).toBe(DEFAULT_MADRASAH_IDENTITY.nsm);
    expect(captured.npsn).toBe(DEFAULT_MADRASAH_IDENTITY.npsn);
    expect(captured.phone).toBe(DEFAULT_MADRASAH_IDENTITY.phone);

    const built = buildInitialStudioContentFromDraft(saved.draft);
    expect(built.includeKopSurat).toBe(true);
    const stripped = stripAutoGeneratedKopNodes(
      built.content.content,
      demo.settings.schoolName
    );
    expect(stripped.length).toBeLessThan(built.content.content.length);
    expect(stripped[0]?.type).not.toBe('horizontalRule');

    const pdfRes = await renderOfficialDocumentPdf({
      draft: saved.draft,
      content: built.content,
      pageSettings: built.pageSettings,
      state: saved.state,
      officialNumber: '001/S.UND/MTs.DA/XI/2026',
    });
    expect(pdfRes.pdfBytes.byteLength).toBeGreaterThan(1500);
    expect(String.fromCharCode(...pdfRes.pdfBytes.slice(0, 5))).toBe('%PDF-');
  });

  it('6. Every feature UI screen renders the unified OfficialKopSuratPreview', () => {
    const demo = createDemoState();
    const tpl01 = SYSTEM_DOCUMENT_TEMPLATES.find((t) => t.id === 'SYS-TPL-01')!;
    const activeTeacherId = demo.teachers.find((t) => t.isActive !== false)!.id;
    const saved = saveIntakeDraftToState(
      demo,
      tpl01,
      {
        peserta: [activeTeacherId],
        nama_kegiatan: 'Workshop Evaluasi Pembelajaran',
        penyelenggara: 'Kantor Kementerian Agama Kota Depok',
        tanggal_mulai: '2026-11-28',
        tanggal_selesai: '2026-11-28',
        lokasi: 'MTs Daruttafsir Al-Husaini',
      },
      { timestamp: '2026-11-18T08:15:00Z' }
    );

    const schedModalHtml = renderToStaticMarkup(
      React.createElement(SchedulePdfExportModal, {
        state: demo,
        selectedClassId: demo.classes[0]?.id ?? '',
        isOpen: true,
        onClose: () => {},
        onNotify: () => {},
      })
    );
    expect(schedModalHtml).toContain('oks-root');
    expect(schedModalHtml).toContain('DARUTTAFSIR AL-HUSAINI');

    const attModalHtml = renderToStaticMarkup(
      React.createElement(AttendancePdfExportModal, {
        state: demo,
        isOpen: true,
        onClose: () => {},
        onNotify: () => {},
      })
    );
    expect(attModalHtml).toContain('oks-root');
    expect(attModalHtml).toContain('DARUTTAFSIR AL-HUSAINI');

    const intakeHtml = renderToStaticMarkup(
      React.createElement(DocumentIntakeForm, {
        state: demo,
        template: tpl01,
        onSaveDraft: () => {},
        onBackToTemplates: () => {},
        onOpenCenter: () => {},
      })
    );
    expect(intakeHtml).toContain('s03-live-kop');
    expect(intakeHtml).toContain('oks-root');
    expect(intakeHtml).toContain('TERAKREDITASI B');

    const studioHtml = renderToStaticMarkup(
      React.createElement(DocumentStudio, {
        state: saved.state,
        draft: saved.draft,
        onPersistStudioState: () => {},
        onBackToIntake: () => {},
        onBackToCenter: () => {},
      })
    );
    expect(studioHtml).toContain('s04-paper-kop-banner');
    expect(studioHtml).toContain('oks-root');
    expect(studioHtml).toContain('DARUTTAFSIR AL-HUSAINI');

    const previewHtml = renderToStaticMarkup(
      React.createElement(DocumentPreviewFinalize, {
        state: saved.state,
        draft: saved.draft,
        onPersistState: async () => {},
        onBackToCenter: () => {},
      })
    );
    expect(previewHtml).toContain('s05-kop-block');
    expect(previewHtml).toContain('oks-root');
    expect(previewHtml).toContain('AHU-0013850.AH.01.12.Tahun 2021');

    const archiveHtml = renderToStaticMarkup(
      React.createElement(DocumentArchiveDetail, {
        state: {
          ...saved.state,
          intakeDrafts: saved.state.intakeDrafts?.map((d) =>
            d.id === saved.draft.id
              ? {
                  ...d,
                  studio: {
                    schemaVersion: 1 as const,
                    editorStatus: 'IN_PROGRESS' as const,
                    content: buildInitialStudioContentFromDraft(saved.draft).content,
                    pageSettings: buildInitialStudioContentFromDraft(saved.draft).pageSettings,
                    updatedAt: '2026-11-18T08:20:00Z',
                  },
                }
              : d
          ),
        },
        documentId: saved.draft.documentId,
        onPersistState: async () => {},
        onBackToCenter: () => {},
      })
    );
    expect(archiveHtml).toContain('oks-root');
    expect(archiveHtml).toContain('DARUTTAFSIR AL-HUSAINI');

    const galleryHtml = renderToStaticMarkup(
      React.createElement(TemplateGallery, {
        state: demo,
      })
    );
    expect(galleryHtml).toContain('oks-root');
    expect(galleryHtml).toContain('DARUTTAFSIR AL-HUSAINI');

    const managerHtml = renderToStaticMarkup(
      React.createElement(TemplateManager, {
        state: demo,
        onPersistState: async () => {},
        onBackToGallery: () => {},
      })
    );
    expect(managerHtml).toContain('oks-root');

    const settingsHtml = renderToStaticMarkup(
      React.createElement(SettingsScreen, {
        state: demo,
        onSettingsChange: () => {},
        onReset: () => {},
        onNotify: () => {},
        saved: true,
      })
    );
    expect(settingsHtml).toBeTruthy();
  });
});
